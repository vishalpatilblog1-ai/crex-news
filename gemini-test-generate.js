import { generateGeminiTweet } from "./ai/generate-gemini-tweet.js";
import { generateGPTCAtweet } from "./cricket-addictor/ai/generateGPTCAtweet.js";
import { isCAArticle } from "./cricket-addictor/caFilters.js";
import { fetchCARSS } from "./cricket-addictor/fetchCARss.js";
import { getCAImageUrl } from "./cricket-addictor/getCAImageUrl.js";
import { parseCAArticle } from "./cricket-addictor/parseCAArticle.js";
import { loadState } from "./utils/stateStoreCloud.js";

async function runTest() {
  global.STATE = await loadState();
  const items = await fetchCARSS();
  const MAX_AGE_MIN = 900;
  // console.log("items", items);
  if (!Array.isArray(items) || items.length === 0) return;

  // ---- select candidate ----
  const sorted = items
    .filter(isCAArticle)
    .sort((a, b) => getPubDate(b) - getPubDate(a));

  let selected = null;

  const item = sorted[4];

  selected = item;

  if (!selected) return;

  const parsed = parseCAArticle(selected);
  const imageUrl = getCAImageUrl(selected);
  console.log("\n");

  console.log("imageUrl::", imageUrl);
  console.log("link::", selected.link);
  if (!parsed?.body || parsed.body.length < 80) return;

  let tweetGeminiText = null;
  let tweetGPTText = null;
  try {
    tweetGeminiText = await generateGeminiTweet(
      `${parsed.headline}\n${parsed.body}`
    );
  } catch (err) {
    console.warn("⚠️ Gemini failed, falling back to GPT:", err?.message || err);
  }

  // if (!tweetGeminiText) {
  try {
    tweetGPTText = await generateGPTCAtweet(
      `${parsed.headline}\n${parsed.body}`
    );
  } catch (err) {
    console.error("❌ GPT also failed:", err?.message || err);
  }
  // }

  const tweetText = tweetGeminiText || tweetGPTText;

  if (!tweetText) {
    console.warn("⚠️ No tweet generated by either model");
    return;
  }

  if (tweetGPTText) {
    console.log("tweetGPTText::::");
    console.log(tweetGPTText);
  }
  console.log("=================================================");
  if (tweetGeminiText) {
    console.log("tweetGeminiText::::");
    console.log(tweetGeminiText);
  }
  // console.log("tweetText>>>>>>", tweetText);
}

runTest();

function getPubDate(item) {
  return item?.pubDate ? new Date(item.pubDate).getTime() : 0;
}
